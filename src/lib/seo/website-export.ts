import type { SeoBlogPost } from "@/lib/db/seo-queries";

/**
 * Phase 32 — Website Blog Export.
 * Turns approved SEO Factory posts into TypeScript blog objects that drop
 * straight into the public PlantPal site's src/lib/blog/posts.ts.
 */

export interface WebsiteBlogPost {
  title: string;
  slug: string;
  metaDescription: string;
  date: string;
  author: string;
  category: string;
  tags: string[];
  featuredImage?: string;
  intro: string;
  sections: { subhead: string; body: string }[];
  faqs: { question: string; answer: string }[];
}

/** Map a Marketing OS post onto the public site's blog shape. */
export function buildWebsiteBlogObject(post: SeoBlogPost): WebsiteBlogPost {
  return {
    title: post.headline || post.seoTitle || post.keyword,
    slug: post.slug,
    metaDescription: post.metaDescription,
    date: (post.publishedAt ?? post.createdAt).slice(0, 10),
    author: post.author || "PlantPal Team",
    category: post.category || "Plant Care",
    tags: post.tags.length > 0 ? post.tags : [post.keyword].filter(Boolean),
    ...(post.featuredImage ? { featuredImage: post.featuredImage } : {}),
    intro: post.intro,
    sections: post.sections,
    faqs: post.faq,
  };
}

/** Escape a string for a single-quoted TS literal. */
function ts(value: string): string {
  return `'${value.replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\r?\n/g, "\\n")}'`;
}

/** Render the post as a TypeScript object literal ready to paste into posts.ts. */
export function renderTsSnippet(obj: WebsiteBlogPost): string {
  const lines: string[] = [];
  lines.push("{");
  lines.push(`  title: ${ts(obj.title)},`);
  lines.push(`  slug: ${ts(obj.slug)},`);
  lines.push(`  metaDescription: ${ts(obj.metaDescription)},`);
  lines.push(`  date: ${ts(obj.date)},`);
  lines.push(`  author: ${ts(obj.author)},`);
  lines.push(`  category: ${ts(obj.category)},`);
  lines.push(`  tags: [${obj.tags.map(ts).join(", ")}],`);
  if (obj.featuredImage) {
    lines.push(`  featuredImage: ${ts(obj.featuredImage)},`);
  }
  lines.push(`  intro: ${ts(obj.intro)},`);
  lines.push("  sections: [");
  for (const s of obj.sections) {
    lines.push("    {");
    lines.push(`      subhead: ${ts(s.subhead)},`);
    lines.push(`      body: ${ts(s.body)},`);
    lines.push("    },");
  }
  lines.push("  ],");
  lines.push("  faqs: [");
  for (const f of obj.faqs) {
    lines.push("    {");
    lines.push(`      question: ${ts(f.question)},`);
    lines.push(`      answer: ${ts(f.answer)},`);
    lines.push("    },");
  }
  lines.push("  ],");
  lines.push("},");
  return lines.join("\n");
}

/** Full .ts file content for the download button. */
export function renderTsFileSnippet(obj: WebsiteBlogPost): string {
  return [
    `// PlantPal blog post: ${obj.title}`,
    `// Generated by Marketing OS SEO Factory on ${new Date().toISOString().slice(0, 10)}`,
    `// Paste this object into the posts array in src/lib/blog/posts.ts`,
    "",
    renderTsSnippet(obj),
    "",
  ].join("\n");
}

